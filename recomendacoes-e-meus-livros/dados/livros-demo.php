function urlCapa(array $livro): string
{
    return 'https://images.unsplash.com/photo-'
        . rawurlencode($livro['capa'])
        . '?w=560&h=800&fit=crop&auto=format';
}

function estrelas(float $nota): string
{
    $estrelasCheias = (int) round($nota);
    $estrelasVazias = 5 - $estrelasCheias;

    return str_repeat('★', $estrelasCheias)
        . str_repeat('☆', $estrelasVazias);
}

function escapar(string $texto): string
{
    return htmlspecialchars($texto, ENT_QUOTES, 'UTF-8');
}
